"""Generate infra/athena/create_tables.sql from the Parquet schemas the pipeline actually writes.

Runs compute/stats.py and compute/evidence.py on the synthetic data from compute/test_stats.py
(no AWS, no network), writes each processed table to Parquet in memory, and maps the Arrow types
to Athena types. Regenerate after changing any table's columns:

    python infra/athena/gen_ddl.py            # rewrite create_tables.sql
    python infra/athena/gen_ddl.py --check    # exit 1 if the file is out of date
"""
import io
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
sys.path[:0] = [ROOT, os.path.join(ROOT, "compute")]

import pyarrow.parquet as pq  # noqa: E402

from compute import evidence as ev  # noqa: E402
from compute import stats  # noqa: E402
import test_stats  # noqa: E402

OUT = os.path.join(os.path.dirname(__file__), "create_tables.sql")
ATHENA_TYPES = {"large_string": "string", "string": "string", "double": "double",
                "int64": "bigint", "date32[day]": "date", "bool": "boolean"}


def build_tables():
    data = test_stats.make_data()
    sens = stats.sensitivities(data)
    links = stats.links(data)
    chains = stats.chain_reconciliation(links, sens)
    holdings = stats.persona_holdings()
    pbeta = stats.portfolio_beta(data, holdings)
    evid = ev.evidence_frame([{
        "evidence_id": "XOM-direct-1", "ticker": "XOM", "doc_type": "10-K", "channel": "direct",
        "direction": "positive", "source_url": "https://example.com", "section": "s", "excerpt": "e",
        "s3_key": "raw/manual_docs/x.pdf"}])
    return {
        "sensitivities": sens,
        "rolling": stats.rolling_betas(data),
        "links": links,
        "chain_reconciliation": chains,
        "duration_check": stats.duration_check(links, sens),
        "persona_holdings": holdings,
        "portfolio_exposure": stats.portfolio_exposure(holdings, sens),
        "portfolio_beta": pbeta,
        "scenarios": stats.scenarios(sens, pbeta),
        "alternatives": stats.alternatives(holdings, sens),
        "evidence": evid,
        "confidence": ev.build_confidence(sens, chains, evid),
        "edges": ev.build_edges(links, evid),
    }


def schemas():
    out = {}
    for name, df in build_tables().items():
        buf = io.BytesIO()
        df.to_parquet(buf, index=False)
        fields = pq.read_schema(io.BytesIO(buf.getvalue()))
        out[name] = [(f.name, ATHENA_TYPES[str(f.type)]) for f in fields if not f.name.startswith("__")]
    return out


def render(tables):
    lines = [
        "-- Athena DDL for the cascade Glue database. GENERATED by infra/athena/gen_ddl.py from the",
        "-- Parquet schemas that compute/stats.py and compute/evidence.py write; do not hand-edit.",
        "-- Run in the Athena console with workgroup `cascade`, ONE statement at a time, top to bottom.",
        "-- Every table reads s3://cascade-s3-bucket/processed/<table>/ (one part-0.parquet each).",
        "",
        "CREATE DATABASE IF NOT EXISTS cascade;",
        "",
    ]
    for name, cols in tables.items():
        width = max(len(c) for c, _ in cols)
        body = ",\n".join("  `%s`%s %s" % (c, " " * (width - len(c)), t) for c, t in cols)
        lines.append("CREATE EXTERNAL TABLE IF NOT EXISTS cascade.%s (\n%s\n)\nSTORED AS PARQUET\n"
                     "LOCATION 's3://cascade-s3-bucket/processed/%s/';\n" % (name, body, name))
    return "\n".join(lines)


if __name__ == "__main__":
    text = render(schemas())
    if "--check" in sys.argv:
        current = open(OUT).read() if os.path.exists(OUT) else ""
        sys.exit(0 if current == text else "create_tables.sql is out of date; run infra/athena/gen_ddl.py")
    open(OUT, "w").write(text)
    print("wrote", OUT)
